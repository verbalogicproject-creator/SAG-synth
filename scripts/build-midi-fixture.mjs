/**
 * scripts/build-midi-fixture.mjs — regenerates the MIDI fixtures.
 *
 *   node scripts/build-midi-fixture.mjs
 *
 * Writes two artifacts from ONE source so they cannot drift:
 *   fixtures/demo.mid        — the real binary, what a user drops on the app
 *   fixtures/demo-midi.json  — the same bytes base64-encoded, which is exactly the
 *                              shape `importMidi { bytes }` takes and what the tests
 *                              import (no node:fs in tests — @types/node is not a
 *                              dependency of this project).
 *
 * The fixture deliberately exercises the hard parts of F70: a mid-song tempo change
 * and a channel-10 drum track.
 *
 * Plain .mjs, not .ts: it is outside tsconfig's include, so it needs no @types/node.
 */

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import pkg from '@tonejs/midi';

const { Midi } = pkg;

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const midi = new Midi();
midi.header.name = 'SAG-synth demo';

// Two tempo events — F70 requires the importer to reproduce every one of them.
midi.header.tempos = [
  { ticks: 0, bpm: 110 },
  { ticks: midi.header.ppq * 4, bpm: 88 },
];
midi.header.update();

// Track 0 — pitched bass line, mirrors fixtures/demo-song.json.
const bass = midi.addTrack();
bass.name = 'Bass';
bass.channel = 0;
bass.instrument.number = 38; // GM Synth Bass 1

const beat = 60 / 110;
const line = [
  [0, 0.45, 36, 1.0],
  [0.5, 0.2, 36, 0.55],
  [1, 0.45, 36, 0.85],
  [1.75, 0.2, 39, 0.6],
  [2, 0.45, 43, 0.9],
  [3, 0.45, 34, 0.75],
  [4, 0.45, 41, 1.0],
  [4.5, 0.2, 41, 0.55],
  [5, 0.45, 41, 0.85],
  [5.75, 0.2, 44, 0.6],
  [6, 0.9, 48, 0.95],
  [7.5, 0.45, 43, 0.7],
];
for (const [beatsIn, beatsLong, midiNote, velocity] of line) {
  bass.addNote({
    midi: midiNote,
    time: beatsIn * beat,
    duration: beatsLong * beat,
    velocity,
  });
}

// Track 1 — channel 10 (index 9). F70 requires this to be flagged as drums rather
// than mapped to pitched synthesis.
const drums = midi.addTrack();
drums.name = 'Drums';
drums.channel = 9;
for (let i = 0; i < 8; i += 1) {
  drums.addNote({ midi: 36, time: i * beat, duration: 0.1, velocity: 0.9 }); // kick
  drums.addNote({ midi: 42, time: (i + 0.5) * beat, duration: 0.1, velocity: 0.5 }); // hat
}

const bytes = midi.toArray();

writeFileSync(join(root, 'fixtures/demo.mid'), bytes);

const base64 = Buffer.from(bytes).toString('base64');
writeFileSync(
  join(root, 'fixtures/demo-midi.json'),
  `${JSON.stringify(
    {
      _comment:
        'Generated by scripts/build-midi-fixture.mjs from fixtures/demo.mid. Same bytes, base64-encoded — this is the exact shape the importMidi command takes.',
      filename: 'demo.mid',
      bytes: base64,
    },
    null,
    2,
  )}\n`,
);

const reparsed = new Midi(bytes);
console.log(
  `wrote fixtures/demo.mid (${bytes.length} bytes), fixtures/demo-midi.json — ` +
    `${reparsed.tracks.length} tracks, ${reparsed.tracks.reduce((n, t) => n + t.notes.length, 0)} notes, ` +
    `${reparsed.header.tempos.length} tempo events, drum channel: ${reparsed.tracks.some((t) => t.channel === 9)}`,
);
